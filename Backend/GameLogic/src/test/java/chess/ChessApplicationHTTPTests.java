	private static final String TEST_USER_ID = "3f2b8c1e-5a47-4d0e-9b6a-1c2d3e4f5a6b";
	private static final String INITIAL_BOARD_FEN = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1";
	private static final String FEN_AFTER_E4 = "rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq e3 0 1";

	/**Stubs the repository so that the given match can be found by id, and so that save() returns what it receives. Since the Match object is mutated in place, later requests see the moves of earlier ones.*/
	private Match givenStoredMatch(Match match){
		when(repository.findById(match.getId())).thenReturn(Optional.of(match));
		when(repository.save(any(Match.class))).thenAnswer(invocation -> invocation.getArgument(0));

		return match;
	}

	private ResultActions postMove(String matchId, String uci) throws Exception{
		return this.mockMvc.perform(post("/logic/games/" + matchId + "/moves").contentType(MediaType.APPLICATION_JSON).content("{\"uci\": \"" + uci + "\"}"));
	}

	/**Test for the function newMatch(@RequestBody CreateGameRequest request)*/
	@Test public void shouldReturnNewMatch() throws Exception{
		when(repository.save(any(Match.class))).thenAnswer(invocation -> invocation.getArgument(0));

		String requestBody = "{\"userId\": \"" + TEST_USER_ID + "\", \"mode\": \"vs_bot\", \"botLevel\": 8, \"playerColor\": \"white\"}";

		this.mockMvc.perform(post("/logic/games").contentType(MediaType.APPLICATION_JSON).content(requestBody))
			.andExpect(status().isCreated())
			.andExpect(jsonPath("$.gameId", notNullValue()))
			.andExpect(jsonPath("$.userId").value(TEST_USER_ID))
			.andExpect(jsonPath("$.status").value("in_progress"))
			.andExpect(jsonPath("$.turn").value("white"))
			.andExpect(jsonPath("$.fen").value(INITIAL_BOARD_FEN))
			.andExpect(jsonPath("$.legalMoves.e2", containsInAnyOrder("e3", "e4")))
			.andDo(
				document(
					"createMatch",
					responseFields(
						fieldWithPath("gameId").description("The identifier (a UUID v4 as a String) for the created match. Generated by Game Logic."),
						fieldWithPath("userId").description("The identifier (a UUID v4 as a String) of the user that owns the match."),
						fieldWithPath("mode").description("String that describes the mode of the match. Takes one of two values: \"local\" | \"vs_bot\""),
						fieldWithPath("botLevel").description("The level of the bot, from 1 to 20. Only present on \"vs_bot\" matches, Null on \"local\" matches."),
						fieldWithPath("playerColor").description("The color of the human player. Takes one of two values: \"white\" | \"black\". Only present on \"vs_bot\" matches, Null on \"local\" matches."),
						fieldWithPath("status").description("String that describes the status of the match. Takes one of two values: \"in_progress\" | \"finished\""),
						fieldWithPath("turn").description("The color that has to move next. Takes one of two values: \"white\" | \"black\""),
						fieldWithPath("fen").description("The FEN representation of the current position of the board."),
						subsectionWithPath("legalMoves").description("Map from an origin square to the list of destination squares that are legal for the piece on it. Empty if the match is finished. For a promotion, the destination square is listed only once, and the client must add the letter of the piece (for example \"e7e8q\")."),
						fieldWithPath("moves").description("A list of the moves that have been made during this match. Each one has the fields ply, san, uci, fenAfter and timestamp."),
						fieldWithPath("result").description("String that describes the end result of this match. Takes one of four values: \"white\" | \"black\" | \"draw\" | Null (in the case that the match hasn't ended)"),
						fieldWithPath("endReason").description("String that describes the reason for the end result of this match. Takes one of five values: \"checkmate\" | \"stalemate\" | \"resignation\" | \"draw\" | Null (in the case that the match hasn't ended)"),
						fieldWithPath("createdAt").description("The date and time in which this match started, in ISO 8601 UTC."),
						fieldWithPath("finishedAt").description("The date and time in which this match ended, in ISO 8601 UTC. Null in the case that the match hasn't ended.")
					)
				)
			);
	}

