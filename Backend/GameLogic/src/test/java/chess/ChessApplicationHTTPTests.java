	/**Test for the function addMovement(@PathVariable String id, @RequestBody MovementCreationEssentials movement)*/
	@Test public void shouldReturnUpdatedStateAfterValidMove() throws Exception{
		Match testMatch = givenStoredMatch(new Match(TEST_USER_ID, "local", null, null));

		postMove(testMatch.getId(), "e2e4")
			.andExpect(status().isOk())
			.andExpect(jsonPath("$.fen").value(FEN_AFTER_E4))
			.andExpect(jsonPath("$.turn").value("black"))
			.andExpect(jsonPath("$.status").value("in_progress"))
			.andExpect(jsonPath("$.moves.length()").value(1))
			.andExpect(jsonPath("$.moves[0].ply").value(1))
			.andExpect(jsonPath("$.moves[0].san").value("e4"))
			.andExpect(jsonPath("$.moves[0].uci").value("e2e4"))
			.andExpect(jsonPath("$.moves[0].fenAfter").value(FEN_AFTER_E4))
			.andExpect(jsonPath("$.legalMoves.e7", containsInAnyOrder("e6", "e5")))
			.andDo(
				document(
					"updateWithValidMove",
					responseFields(
						fieldWithPath("gameId").description("The identifier of the match, the same that was used on the POST request."),
						fieldWithPath("userId").description("The identifier of the user that owns the match."),
						fieldWithPath("mode").description("\"local\" | \"vs_bot\""),
						fieldWithPath("botLevel").description("Null, since this is a \"local\" match."),
						fieldWithPath("playerColor").description("Null, since this is a \"local\" match."),
						fieldWithPath("status").description("\"in_progress\" | \"finished\""),
						fieldWithPath("turn").description("The color that has to move next, after performing the specified move."),
						fieldWithPath("fen").description("The FEN representation for the game board after performing the specified move."),
						subsectionWithPath("legalMoves").description("Map from an origin square to the list of destination squares that are legal in the new position."),
						subsectionWithPath("moves").description("A list of the moves that have been made during this match. Each one has the fields ply (the number of the move, starting at 1), san (the move written for the user, for example \"e4\"), uci (for example \"e2e4\"), fenAfter (the board after the move) and timestamp."),
						fieldWithPath("result").description("Null, since the match hasn't ended."),
						fieldWithPath("endReason").description("Null, since the match hasn't ended."),
						fieldWithPath("createdAt").description("The date and time in which this match started."),
						fieldWithPath("finishedAt").description("Null, since the match hasn't ended.")
					)
				)
			);
	}

