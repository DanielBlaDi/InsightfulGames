	/**Test for the function addMovement(@PathVariable String id, @RequestBody MovementCreationEssentials movement), playing the Fool's Mate*/
	@Test public void shouldFinishMatchOnCheckmate() throws Exception{
		Match testMatch = givenStoredMatch(new Match(TEST_USER_ID, "local", null, null));

		postMove(testMatch.getId(), "f2f3").andExpect(status().isOk());
		postMove(testMatch.getId(), "e7e5").andExpect(status().isOk());
		postMove(testMatch.getId(), "g2g4").andExpect(status().isOk());

		postMove(testMatch.getId(), "d8h4")
			.andExpect(status().isOk())
			.andExpect(jsonPath("$.status").value("finished"))
			.andExpect(jsonPath("$.result").value("black"))
			.andExpect(jsonPath("$.endReason").value("checkmate"))
			.andExpect(jsonPath("$.finishedAt", notNullValue()))
			.andExpect(jsonPath("$.legalMoves").isEmpty())
			.andExpect(jsonPath("$.moves.length()").value(4))
			.andExpect(jsonPath("$.moves[3].san").value("Qh4#"))
			.andDo(
				document(
					"finishMatchByCheckmate",
					responseFields(
						fieldWithPath("gameId").description("The identifier of the match."),
						fieldWithPath("userId").description("The identifier of the user that owns the match."),
						fieldWithPath("mode").description("\"local\" | \"vs_bot\""),
						fieldWithPath("botLevel").description("Null, since this is a \"local\" match."),
						fieldWithPath("playerColor").description("Null, since this is a \"local\" match."),
						fieldWithPath("status").description("\"finished\", since the last move was a checkmate."),
						fieldWithPath("turn").description("The color that would have to move next. In a checkmate, it is the color that lost."),
						fieldWithPath("fen").description("The FEN representation of the final position of the board."),
						subsectionWithPath("legalMoves").description("Empty, since the match is finished."),
						subsectionWithPath("moves").description("A list of all the moves of the match."),
						fieldWithPath("result").description("The color that won: \"white\" | \"black\". It is \"draw\" in the case of a draw."),
						fieldWithPath("endReason").description("The reason the match ended: \"checkmate\" | \"stalemate\" | \"resignation\" | \"draw\""),
						fieldWithPath("createdAt").description("The date and time in which this match started."),
						fieldWithPath("finishedAt").description("The date and time in which this match ended.")
					)
				)
			);
	}

